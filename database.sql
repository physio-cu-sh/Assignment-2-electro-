drop policy if exists "team35 public read students" on public.team35_students;
create policy "team35 public read students" on public.team35_students for select to anon, authenticated using (true);
drop policy if exists "team35 public read teams" on public.team35_teams;
create policy "team35 public read teams" on public.team35_teams for select to anon, authenticated using (true);
drop policy if exists "team35 public read bookings" on public.team35_bookings;
create policy "team35 public read bookings" on public.team35_bookings for select to anon, authenticated using (true);
drop policy if exists "team35 public create booking" on public.team35_bookings;
create policy "team35 public create booking" on public.team35_bookings for insert to anon, authenticated with check (exists(select 1 from public.team35_students s where s.id=student_id) and exists(select 1 from public.team35_teams t where t.id=team_id and slot_number between 1 and t.capacity));
drop policy if exists "team35 admin delete booking" on public.team35_bookings;
create policy "team35 admin delete booking" on public.team35_bookings for delete to authenticated using (exists(select 1 from public.ptcu_admins a where a.user_id=(select auth.uid())));
grant select on public.team35_students, public.team35_teams, public.team35_bookings to anon, authenticated;
