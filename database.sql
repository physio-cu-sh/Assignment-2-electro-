create table if not exists public.team35_students (
 id bigint generated by default as identity primary key,
 full_name text not null unique,
 created_at timestamptz not null default now()
);
create table if not exists public.team35_teams (
 id int primary key,
 team_name text not null,
 capacity int not null default 5 check (capacity = 5)
);
create table if not exists public.team35_bookings (
 id bigint generated by default as identity primary key,
 student_id bigint not null unique references public.team35_students(id) on delete cascade,
 team_id int not null references public.team35_teams(id) on delete cascade,
 slot_number int not null check (slot_number between 1 and 5),
 created_at timestamptz not null default now(),
 unique(team_id, slot_number)
);
